/**
 * Builds the offline keyword index for Find a verse from the bundled, hash-verified Bible snapshots.
 * Run with `npm run build:search`. Output is deterministic; tests rebuild it and compare hashes.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { BIBLE_SNAPSHOT, KJV_SNAPSHOT } from '../src/bible-version.ts';
import { encodePostings, VerseTable, type IndexMeta } from '../src/search/index-format.ts';
import { terms } from '../src/search/normalize.ts';

interface Manifest { translations: Record<string, { books: { id: string; chapters: { number: number; path: string; verses: number[] }[] }[] }> }
const sha256 = (bytes: Uint8Array | string) => createHash('sha256').update(bytes).digest('hex');

export function buildSearchIndex(root = 'public/bibles') {
  const sources = [BIBLE_SNAPSHOT, KJV_SNAPSHOT];
  const editions = sources.flatMap(snapshot => {
    const manifest = JSON.parse(readFileSync(join(root, snapshot, 'manifest.json'), 'utf8')) as Manifest;
    return Object.values(manifest.translations).map(edition => ({ snapshot, edition }));
  });
  const order = editions[0].edition.books.map(b => b.id);
  const highest = new Map<string, number[]>(order.map(id => [id, []]));
  for (const { edition } of editions) for (const book of edition.books) {
    const counts = highest.get(book.id);
    if (!counts) throw new Error(`Unknown book ${book.id}`);
    for (const chapter of book.chapters) counts[chapter.number - 1] = Math.max(counts[chapter.number - 1] ?? 0, ...chapter.verses);
  }
  const books = order.map(id => [id, highest.get(id)!] as [string, number[]]);
  if (books.some(([, counts]) => counts.some(c => !c))) throw new Error('A chapter is missing from every translation.');
  const table = new VerseTable(books);
  const verseTerms = table.refs.map(() => new Set<string>());
  for (const { snapshot, edition } of editions) for (const book of edition.books) for (const chapter of book.chapters) {
    const data = JSON.parse(readFileSync(join(root, snapshot, chapter.path), 'utf8')) as { verses: Record<string, string> };
    for (const [verse, text] of Object.entries(data.verses)) {
      const ordinal = table.ordinal(book.id, chapter.number, Number(verse));
      if (ordinal === undefined) throw new Error(`Unmapped verse ${book.id} ${chapter.number}:${verse}`);
      for (const term of terms(text)) verseTerms[ordinal].add(term);
    }
  }
  const lists = new Map<string, number[]>();
  verseTerms.forEach((set, ordinal) => { for (const term of set) (lists.get(term) ?? lists.set(term, []).get(term)!).push(ordinal); });
  const vocab = [...lists.keys()].sort();
  const lengths = Uint8Array.from(verseTerms, set => Math.min(255, set.size));
  const postings = encodePostings(vocab.map(term => lists.get(term)!), lengths);
  const meta: IndexMeta = { format: 'verse-recall-search', version: 1, sources, books, vocab, postingsSha256: sha256(postings) };
  const metaJson = JSON.stringify(meta);
  const id = `s1-${sha256(metaJson).slice(0, 16)}`;
  return { id, metaJson, metaSha256: sha256(metaJson), postings };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const built = buildSearchIndex();
  const out = join('public', 'search');
  mkdirSync(out, { recursive: true });
  for (const old of readdirSync(out)) if (old !== built.id) rmSync(join(out, old), { recursive: true });
  mkdirSync(join(out, built.id), { recursive: true });
  writeFileSync(join(out, built.id, 'meta.json'), built.metaJson);
  writeFileSync(join(out, built.id, 'postings.bin'), built.postings);
  writeFileSync('src/search/version.ts', `// Generated by tools/build-search-index.ts. Do not edit.
export const SEARCH_INDEX = '${built.id}';
export const SEARCH_META_SHA256 = '${built.metaSha256}';
`);
  console.log(`${built.id}: meta ${built.metaJson.length} bytes, postings ${built.postings.length} bytes`);
}
